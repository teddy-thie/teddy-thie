#!/usr/bin/env node
// Prints a Figma plugin script that checks the Figma file against tokens.json.
//
//   node tools/figma-check.mjs > /tmp/figma-check.js
//
// Run the printed script in the design-system file: through Claude's Figma connection (use_figma),
// or in Figma under Plugins → Development → Open console, wrapped in an async function.
// It reports:
//   - variables missing from Figma, extra in Figma, or with a different value or code syntax
//   - any layer inside a component or the review frame whose fill or stroke colour, padding, gap,
//     corner radius or min height is a raw value instead of a variable, or whose text has no
//     text style. Zero values, 1–2px stroke weights and text inside instances are allowed.

import { figmaData } from './figma-tokens.mjs';

const { vars } = figmaData();
const r4 = x => Math.round(x * 10000) / 10000;
const compact = (type, values) => type !== 'COLOR' ? values : Object.fromEntries(Object.entries(values).map(([m, c]) => [m, { r: r4(c.r), g: r4(c.g), b: r4(c.b), a: c.a }]));
const expected = vars.map(v => [v.collection, v.name, v.type, compact(v.type, v.values), `var(${v.css})`]);

const script = `// Generated by tools/figma-check.mjs from tokens.json. Do not edit by hand.
const EXPECTED = ${JSON.stringify(expected)};
const close = (a, b) => Math.abs(a - b) < 0.002;
const sameColour = (a, b) => close(a.r, b.r) && close(a.g, b.g) && close(a.b, b.b) && close(a.a ?? 1, b.a ?? 1);

const collections = await figma.variables.getLocalVariableCollectionsAsync();
const all = await figma.variables.getLocalVariablesAsync();
const problems = { missing: [], extra: [], wrongValue: [], wrongCodeSyntax: [], unbound: [] };
const seen = new Set();
for (const [collName, name, type, values, syntax] of EXPECTED) {
  const coll = collections.find(c => c.name === collName);
  const v = coll && all.find(x => x.variableCollectionId === coll.id && x.name === name);
  if (!v) { problems.missing.push(collName + '/' + name); continue; }
  seen.add(v.id);
  if (v.codeSyntax.WEB !== syntax) problems.wrongCodeSyntax.push(name + ': ' + v.codeSyntax.WEB + ' ≠ ' + syntax);
  for (const [modeName, want] of Object.entries(values)) {
    const mode = coll.modes.find(m => m.name === modeName);
    const got = mode && v.valuesByMode[mode.modeId];
    const ok = type === 'COLOR' ? got && sameColour(got, want) : type === 'FLOAT' ? typeof got === 'number' && close(got, want) : got === want;
    if (!ok) problems.wrongValue.push(name + ' (' + modeName + '): ' + JSON.stringify(got) + ' ≠ ' + JSON.stringify(want));
  }
}
for (const v of all) if (!seen.has(v.id)) problems.extra.push(v.name);

// Layers: everything inside component sets, components and the review frame, on every page.
const BOUND_FIELDS = ['paddingTop', 'paddingRight', 'paddingBottom', 'paddingLeft', 'itemSpacing', 'counterAxisSpacing', 'topLeftRadius', 'topRightRadius', 'bottomLeftRadius', 'bottomRightRadius', 'minHeight', 'minWidth'];
let checked = 0;
function inspect(n, path) {
  if (n.type === 'INSTANCE') { checked++; return; } // instances inherit their main component's bindings
  checked++;
  const where = path + ' › ' + n.name;
  for (const key of ['fills', 'strokes']) {
    const paints = n[key];
    if (!Array.isArray(paints)) continue;
    paints.forEach((p, i) => { if (p.visible !== false && p.type === 'SOLID' && !(p.boundVariables && p.boundVariables.color)) problems.unbound.push(where + ': ' + key + '[' + i + '] is a raw colour'); });
  }
  for (const f of BOUND_FIELDS) {
    if (!(f in n)) continue;
    const val = n[f];
    if (typeof val !== 'number' || val === 0 || val === null) continue;
    if (f.startsWith('padding') || f === 'itemSpacing' || f === 'counterAxisSpacing') { if (!('layoutMode' in n) || n.layoutMode === 'NONE') continue; }
    if (!(n.boundVariables && n.boundVariables[f])) problems.unbound.push(where + ': ' + f + ' = ' + val + ' is not a variable');
  }
  if (n.type === 'TEXT' && (!n.textStyleId || typeof n.textStyleId !== 'string')) problems.unbound.push(where + ': text has no text style');
  if (Array.isArray(n.effects) && n.effects.length && !n.effectStyleId) problems.unbound.push(where + ': shadow is not an effect style');
  if ('children' in n) for (const c of n.children) inspect(c, where);
}
const page = figma.currentPage;
for (const top of page.children) {
  if (top.type === 'COMPONENT_SET' || top.type === 'COMPONENT' || /^Review/.test(top.name)) inspect(top, page.name);
}
const counts = Object.fromEntries(Object.entries(problems).map(([k, v]) => [k, v.length]));
return {
  pass: Object.values(counts).every(n => n === 0),
  variables: { expected: EXPECTED.length, inFigma: all.length },
  layersChecked: checked,
  counts,
  problems,
};
`;
process.stdout.write(script);
