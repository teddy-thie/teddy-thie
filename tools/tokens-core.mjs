// Shared token functions: read tokens.json, name each token's CSS custom property, and write tokens.css.
// Also the WCAG contrast check for the colour pairs listed in tokens.json.
// Used by build-tokens.mjs, check-tokens.mjs and figma-tokens.mjs.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ROOT = root;
export const TOKENS_PATH = path.join(root, 'tokens.json');
export const CSS_PATH = path.join(root, 'site/css/tokens.css');
const FLUID = 'cc.tedthie.fluid';

// How a token's path becomes a CSS custom property name.
const FONT_PREFIX = { family: 'f-', size: 'text-', fluid: '', leading: 'leading-', tracking: 'tracking-', weight: 'weight-' };
export function cssName(p) {
  const leaf = p[p.length - 1];
  switch (p[0]) {
    case 'color': case 'gradient': case 'shadow': case 'layout': return `--${leaf}`;
    case 'font': return `--${FONT_PREFIX[p[1]]}${leaf}`;
    case 'space': return `--space-${leaf}`;
    case 'radius': return `--radius-${leaf}`;
    default: throw new Error(`No naming rule for ${p.join('.')}`);
  }
}

// Every token as { path, name, type, value, css, description, fluid }, in file order.
export function flatten(tree) {
  const out = [];
  (function walk(node, p, type) {
    if (node.$type) type = node.$type;
    if ('$value' in node) {
      out.push({ path: p, name: cssName(p), type, value: node.$value, description: node.$description || '', fluid: node.$extensions?.[FLUID] || null });
      return;
    }
    for (const [k, v] of Object.entries(node)) if (!k.startsWith('$') && v && typeof v === 'object') walk(v, [...p, k], type);
  })(tree, [], undefined);

  const byPath = new Map(out.map(t => [t.path.join('.'), t]));
  const names = new Set();
  for (const t of out) {
    if (names.has(t.name)) throw new Error(`Two tokens would both be ${t.name}`);
    names.add(t.name);
    let v = t.fluid ? `clamp(${t.fluid.min}, ${t.fluid.vw}, ${t.fluid.max})` : String(t.value);
    // {group.token} aliases become var(--name), so a change to the base token flows through.
    v = v.replace(/\{([^}]+)\}/g, (_, ref) => {
      const target = byPath.get(ref);
      if (!target) throw new Error(`${t.path.join('.')} points at {${ref}}, which doesn't exist`);
      return `var(${target.name})`;
    });
    t.css = v;
  }
  return out;
}

export function buildCss(tokens) {
  const groups = new Map();
  for (const t of tokens) {
    const key = t.path[0] === 'color' || t.path[0] === 'font' ? `${t.path[0]} · ${t.path[1]}` : t.path[0];
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(t);
  }
  let css = `/* Design tokens for tedthie.cc.
   GENERATED by tools/build-tokens.mjs from tokens.json. Do not edit this file:
   change tokens.json and run \`node tools/build-tokens.mjs\`. */

:root {
`;
  for (const [key, list] of groups) {
    css += `\n  /* ${key} */\n`;
    const width = Math.max(...list.map(t => t.name.length));
    for (const t of list) css += `  ${(t.name + ':').padEnd(width + 1)} ${t.css};\n`;
  }
  return css + '}\n';
}

export function load() {
  return flatten(JSON.parse(readFileSync(TOKENS_PATH, 'utf8')));
}

// ---------- contrast (WCAG 2.x relative luminance) ----------
function rgb(value) {
  const s = String(value).trim();
  if (s.startsWith('#')) { const h = s.slice(1); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)); }
  const m = s.match(/rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)/);
  return m ? [+m[1], +m[2], +m[3]] : null;
}
const lum = ([r, g, b]) => [r, g, b].map(c => { c /= 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; }).reduce((a, c, i) => a + c * [0.2126, 0.7152, 0.0722][i], 0);
export const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

export function contrastResults(tokens) {
  const tree = JSON.parse(readFileSync(TOKENS_PATH, 'utf8'));
  const pairs = tree.$extensions?.['cc.tedthie.contrast']?.pairs || [];
  const byPath = new Map(tokens.map(t => [t.path.join('.'), t]));
  return pairs.map(([fg, bg, use, min]) => {
    const f = byPath.get(fg), b = byPath.get(bg);
    if (!f || !b) throw new Error(`Contrast pair points at a missing token: ${fg} on ${bg}`);
    const r = Math.floor(ratio(rgb(f.value), rgb(b.value)) * 100) / 100;
    return { fg: f, bg: b, use, min, ratio: r, pass: r >= min, level: r >= 7 ? 'AAA' : r >= 4.5 ? 'AA' : r >= 3 ? 'AA large' : 'Fails' };
  });
}
